/*
## 核心答案：贪心之所以正确，是因为**可达集合永远是连续区间**，它本质上就是 BFS 分层

### 1. 先看清楚结构

定义 `R_k` = **用不超过 k 次跳跃，能到达的最远下标**。

递归关系：

\[
R_0 = 0,\qquad R_{k+1} = \max_{0 \le i \le R_k}\;(i + nums[i])
\]

为什么是 `i ≤ R_k` 而不是某个具体位置？因为有个关键性质：

> **用不超过 k 次跳跃能到达的下标集合，恰好是连续区间 `[0, R_k]`。**

归纳证明：k=0 时是 `[0,0]`。假设 k 时成立，那么第 k+1 跳可以从 `[0, R_k]` 中**任意**位置 i 出发，跳到 `[i, i+nums[i]]` 内**任意**位置（可以少跳几步）。这些区间的并集，加上左端点 0 始终可达，正好覆盖 `[0, R_{k+1}]`。

这个"连续区间"性质是贪心成立的地基 —— 在一般图上，"每次取最远"是错的，这里对是因为可达域没有洞。

### 2. 你的代码正是在一趟扫描里算出 `R_0, R_1, R_2, ...`

| 变量 | 含义 |
|---|---|
| `curUnlock` | 当前层右边界 `R_k` |
| `maxUnlock` | 正在扫描 `[0, R_k]` 时积累出来的 `R_{k+1}` |
| `i == curUnlock` | 当前层刚好扫描完 → `R_{k+1}` 已确定 → 跳一层 |

所以 `ans` 数的就是层数，`curUnlock = maxUnlock` 就是层与层的推进。**它不是在"猜"，而是在精确计算 `R_k` 序列。**

### 3. 最优性证明（交换/归纳论证）

设最优解用 `k` 步跳完，落点为 `p_0=0, p_1, ..., p_k = n-1`。

断言：`R_j >= p_j`（对所有 j）。

- j=0：`R_0 = 0 = p_0` ✓
- 若 `R_j >= p_j`，则
  \[
  R_{j+1} = \max_{i \le R_j}(i+nums[i]) \;\ge\; p_j + nums[p_j] \;\ge\; p_{j+1}
  \]
  （第一个 ≥ 是因为 `p_j` 在取 max 的范围内；第二个 ≥ 是因为最优解从 `p_j` 一跳最远也只能到 `p_j + nums[p_j]`）

于是 `R_k >= p_k = n-1`，即贪心也能在 k 步内到达 → 贪心步数 ≤ 最优步数。而最优步数 ≤ 任何解的步数，所以**贪心步数 = 最优步数**。∎

一句话概括：**任何策略第 j 跳之后的落点，都不会超过贪心第 j 层的边界 `R_j`。贪心在每一层都拿到了该层能达到的最大上界，谁也超不过它。**

### 4. 一个必须澄清的易错点

注释里写的"每次跳槽都选择能够帮助你升级最多的公司"，容易误解成**站在当前位置跳到最远处**。那是不对的！

反例 `[2,3,1,1,4]`：

- ❶ "每次跳最远"：`0 →(跳2) 2 →(跳1) 3 →(跳1) 4`，**3 步** ❌
- ❷ 正确的分层贪心：第 1 层 `[0]` 得到 `R_1 = 2`；第 2 层是 `[1,2]`，在**整层里**取 max：`max(1+3, 2+1) = 4 >= 4`，**2 步** ✓

差别在于：❶ 只在"我脚下这个位置"取最远；❷ 在"当前层所有能落脚的位置"里取最远。`nums[i]` 是**最大**跳跃长度，不是必须跳满，所以 `0` 跳到 `1` 也是合法的，而 `1` 的跳力比 `2` 强得多。

所以更准确的说法是：**不是"选择升级最多的那一个公司"，而是"把当前能入的所有公司全看一遍，取其中能解锁的最高等级"** —— 因为它们是同一层，步数代价相同，取最大的那个必然不劣于取其他任何一个（支配性）。

### 5. 关于 `jump_2`（反向贪心）

它的思路是"找最靠左的、能一步到终点的位置"，然后把它当新终点递归。正确性来自同一个区间性质：能一步到达 `position` 的位置集合是 `[L, position-1]`（连续！），取最左的 `L`，等价于正向分层往前推一层。两者是同一个 BFS，只是一个从前往后、一个从后往前。

### 小结

| 问题 | 结论 |
|---|---|
| 为什么可以贪心 | 可达域恒为连续区间 `[0, R_k]`，无洞 |
| 贪心在算什么 | 精确计算 BFS 每层边界 `R_k`，不是猜测 |
| 为什么最优 | 任意策略第 j 跳落点 ≤ `R_j`，无法超越 |
| 常见误解 | 不是"脚下跳最远"，是"整层取最远" |

你的 `jump` 实现是对的，只需注意一点：`nums.size() - 1` 是 `size_t`（无符号），建议先 `int n = nums.size();` 再写 `i < n - 1`，避免 `n == 0` 时下溢（本题 `n >= 1` 所以实际不会触发，但养成习惯）。
*/
